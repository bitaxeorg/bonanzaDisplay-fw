#!/usr/bin/env python3
"""Convert the LVGL Editor font and logo data into fixed-cell tables.

The retro UI in ui/app draws straight into an L8 framebuffer, so it needs the
glyphs as plain row bitmaps rather than LVGL's packed bitstreams. This script
reads the editor-generated C files (never the TTFs) so both renderers show
exactly the same pixels.

    python3 tools/gen_ui_assets.py        # rewrites ui/app/bz_assets_data.c
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "ui" / "app" / "bz_assets_data.c"


def c_bytes(text):
    return [int(v, 16) for v in re.findall(r"0x[0-9a-fA-F]+", text)]


def parse_font(path, cell_w, cell_h):
    src = path.read_text()
    bitmap = c_bytes(re.search(r"glyph_bitmap\[\]\s*=\s*\{(.*?)\};", src, re.S).group(1))
    dsc = re.search(r"glyph_dsc\[\]\s*=\s*\{(.*?)\};", src, re.S).group(1)
    glyphs = re.findall(
        r"\.bitmap_index = (\d+), \.adv_w = (\d+), \.box_w = (\d+), "
        r"\.box_h = (\d+), \.ofs_x = (-?\d+), \.ofs_y = (-?\d+)", dsc)
    line_height = int(re.search(r"\.line_height = (\d+)", src).group(1))
    base_line = int(re.search(r"\.base_line = (\d+)", src).group(1))
    start, length = map(int, re.search(
        r"\.range_start = (\d+), \.range_length = (\d+)", src).groups())
    if start != 0x20 or length != 95 or len(glyphs) != 96:
        sys.exit(f"{path.name}: expected one printable-ASCII range")

    rows = []
    for index, adv, box_w, box_h, ofs_x, ofs_y in (tuple(map(int, g)) for g in glyphs[1:]):
        if adv != cell_w * 16:
            sys.exit(f"{path.name}: font is not {cell_w}px monospace")
        cell = [0] * cell_h
        top = line_height - base_line - ofs_y - box_h
        for n in range(box_w * box_h):
            if bitmap[index + n // 8] & (0x80 >> (n % 8)):
                x, y = ofs_x + n % box_w, top + n // box_w
                if not (0 <= x < cell_w and 0 <= y < cell_h):
                    sys.exit(f"{path.name}: glyph pixel outside {cell_w}x{cell_h} cell")
                cell[y] |= 0x80 >> x
        rows.append(cell)
    return rows


def parse_logo(path):
    src = path.read_text()
    data = c_bytes(re.search(r"_map\[\]\s*=\s*\{(.*?)\};", src, re.S).group(1))
    w = int(re.search(r"\.w = (\d+)", src).group(1))
    h = int(re.search(r"\.h = (\d+)", src).group(1))
    if len(data) != w * h:
        sys.exit(f"{path.name}: expected {w}x{h} L8 pixels")
    # One bit per pixel: the logo is a single brightness level in the source.
    stride = (w + 7) // 8
    bits = [0] * (stride * h)
    for i, value in enumerate(data):
        if value >= 0x40:
            bits[(i // w) * stride + (i % w) // 8] |= 0x80 >> ((i % w) % 8)
    return w, h, bits


def emit_table(name, rows, cell_h):
    lines = [f"const uint8_t {name}[95][{cell_h}] = {{"]
    for code, cell in enumerate(rows, start=0x20):
        label = chr(code) if chr(code) not in "\\" else "backslash"
        lines.append("    {" + ",".join(f"0x{b:02x}" for b in cell) + f"}}, /* {label} */")
    lines.append("};")
    return "\n".join(lines)


def main():
    small = parse_font(ROOT / "ui/fonts/portfolio_6x8_data.c", 6, 8)
    large = parse_font(ROOT / "ui/fonts/fmtowns_8x16_data.c", 8, 16)
    w, h, logo = parse_logo(ROOT / "ui/images/bitaxe_logo_data.c")
    body = [
        "/* Generated by tools/gen_ui_assets.py from the LVGL Editor font and",
        " * logo data. Do not edit; re-run the script instead. */",
        '#include "bz_gfx.h"',
        "",
        emit_table("bz_font_small_data", small, 8),
        "",
        emit_table("bz_font_large_data", large, 16),
        "",
        f"const uint8_t bz_logo_w = {w};",
        f"const uint8_t bz_logo_h = {h};",
        f"const uint8_t bz_logo_bits[{len(logo)}] = {{",
    ]
    for i in range(0, len(logo), 12):
        body.append("    " + ",".join(f"0x{b:02x}" for b in logo[i:i + 12]) + ",")
    body.append("};")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(body) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
