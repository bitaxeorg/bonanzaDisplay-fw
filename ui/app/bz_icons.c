void bz_icon(int x, int y, bz_metric_t metric, int level) {
    if (metric >= BZ_M_COUNT || !icons[metric][0]) return;
    for (int row = 0; row < ROWS; ++row)
        for (int col = 0; col < BZ_ICON_SIZE; ++col)
            if (icons[metric][row][col] == '#') bz_px(x + col, y + row, level);
}
